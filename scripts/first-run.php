<?php

declare(strict_types=1);

/**
 * Interactive first-run setup for Windows start.bat
 * Optional args: --host= --port= --user= --pass= --db= --admin-name= --admin-email= --admin-pass=
 */

require_once dirname(__DIR__) . '/app/Helpers.php';
require_once dirname(__DIR__) . '/app/Database.php';

function out(string $msg): void
{
    fwrite(STDOUT, $msg . PHP_EOL);
}

function ask(string $prompt, string $default = ''): string
{
    if ($default !== '') {
        fwrite(STDOUT, $prompt . " [{$default}]: ");
    } else {
        fwrite(STDOUT, $prompt . ': ');
    }
    $line = fgets(STDIN);
    if ($line === false) {
        return $default;
    }
    $line = trim($line);
    return $line === '' ? $default : $line;
}

function parseArgs(array $argv): array
{
    $out = [];
    foreach ($argv as $arg) {
        if (str_starts_with($arg, '--') && str_contains($arg, '=')) {
            [$k, $v] = explode('=', substr($arg, 2), 2);
            $out[$k] = $v;
        }
    }
    return $out;
}

$args = parseArgs($argv);
$configFile = config_path();

if (is_file($configFile)) {
    out('پیکربندی قبلی پیدا شد؛ راه‌اندازی اولیه رد می‌شود.');
    exit(0);
}

out('=== راه‌اندازی اولیه روندینو ===');
out('اطلاعات اتصال MySQL محلی را یک‌بار وارد کنید.');

$host = $args['host'] ?? ask('آدرس میزبان MySQL', '127.0.0.1');
$port = (int) ($args['port'] ?? ask('پورت', '3306'));
$user = $args['user'] ?? ask('نام کاربری', 'root');
$pass = array_key_exists('pass', $args) ? (string) $args['pass'] : ask('رمز عبور (می‌تواند خالی باشد)', '');
$dbName = $args['db'] ?? ask('نام پایگاه داده', 'rondino_simple');

try {
    $server = Database::connectServer($host, $port, $user, $pass);
} catch (Throwable $e) {
    out('خطا: اتصال به MySQL برقرار نشد.');
    out($e->getMessage());
    out('سرویس MySQL Server را روشن کنید و دوباره start.bat را اجرا کنید.');
    exit(1);
}

try {
    $server->exec('CREATE DATABASE IF NOT EXISTS `' . str_replace('`', '``', $dbName) . '` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci');
    out("پایگاه «{$dbName}» آماده شد (ایجاد یا استفاده از موجود).");
} catch (Throwable $e) {
    out('ساخت پایگاه ممکن نشد؛ تلاش برای استفاده از پایگاه موجود…');
    out($e->getMessage());
}

try {
    $dsn = "mysql:host={$host};port={$port};dbname={$dbName};charset=utf8mb4";
    $pdo = new PDO($dsn, $user, $pass, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
} catch (Throwable $e) {
    out('خطا: به پایگاه داده متصل نشدیم. یک پایگاه خالی بسازید یا دسترسی ایجاد بدهید.');
    out($e->getMessage());
    exit(1);
}

$hasSources = false;
try {
    $chk = $pdo->query("SHOW TABLES LIKE 'sources'");
    if ($chk && $chk->fetch()) {
        $hasSources = (int) $pdo->query('SELECT COUNT(*) FROM sources')->fetchColumn() > 0;
    }
} catch (Throwable $e) {
    $hasSources = false;
}

if ($hasSources) {
    out('طرح‌واره از قبل وجود دارد؛ SQL نصب دوباره اجرا نمی‌شود.');
} else {
    $sqlFile = base_path('database/rondino-install.sql');
    try {
        Database::importSqlFile($pdo, $sqlFile);
        $n = (int) $pdo->query('SELECT COUNT(*) FROM sources')->fetchColumn();
        out("SQL نصب شد. تعداد منابع: {$n}");
        if ($n !== 13) {
            out('هشدار: انتظار ۱۳ منبع بود.');
        }
    } catch (Throwable $e) {
        out('خطا در وارد کردن SQL: ' . $e->getMessage());
        exit(1);
    }
}

$cfg = [
    'db' => [
        'host' => $host,
        'port' => $port,
        'name' => $dbName,
        'user' => $user,
        'pass' => $pass,
        'charset' => 'utf8mb4',
    ],
    'setup_token' => '',
    'app_name' => 'روندینو',
    'auto_refresh_minutes' => 30,
    'http_timeout' => 25,
    'http_user_agent' => 'RondinoSimple/1.0 (+private research team)',
];

$export = "<?php\n\n// Generated by first-run. Do not commit.\nreturn " . var_export($cfg, true) . ";\n";
if (file_put_contents($configFile, $export) === false) {
    out('نتوانستیم config/local.php را بنویسیم.');
    exit(1);
}
out('تنظیمات در config/local.php ذخیره شد.');

$name = $args['admin-name'] ?? ask('نام مدیر تیم');
$email = $args['admin-email'] ?? ask('ایمیل مدیر');
$pass1 = $args['admin-pass'] ?? ask('رمز عبور مدیر (حداقل ۸ کاراکتر)');
if (!isset($args['admin-pass'])) {
    $pass2 = ask('تکرار رمز عبور مدیر');
    if ($pass1 !== $pass2) {
        out('رمزها یکسان نیستند.');
        @unlink($configFile);
        exit(1);
    }
}

if ($name === '' || !filter_var($email, FILTER_VALIDATE_EMAIL) || strlen($pass1) < 8) {
    out('نام، ایمیل معتبر و رمز حداقل ۸ کاراکتری لازم است.');
    @unlink($configFile);
    exit(1);
}

$hash = password_hash($pass1, PASSWORD_DEFAULT);
$adminCount = (int) $pdo->query('SELECT COUNT(*) FROM users WHERE is_admin = 1')->fetchColumn();
if ($adminCount > 0) {
    out('مدیر از قبل وجود دارد؛ ایجاد نشد.');
} else {
    $ins = $pdo->prepare('INSERT INTO users (name, email, password_hash, is_admin, is_active, created_at) VALUES (?,?,?,1,1,UTC_TIMESTAMP())');
    $ins->execute([$name, $email, $hash]);
    out('مدیر تیم ساخته شد.');
}

out('راه‌اندازی کامل شد.');
exit(0);
